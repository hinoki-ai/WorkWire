const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("wwApi", {
  // This exposes only an opt-in boolean. Diagnostic samples never include the
  // environment or any transfer paths/tokens.
  diagnosticsEnabled: process.env.WW_PERF_DIAGNOSTICS === "1",
  getState: () => ipcRenderer.invoke("ww:get-state"),
  closeWindow: () => ipcRenderer.invoke("ww:close-window"),
  autoLink: () => ipcRenderer.invoke("ww:auto-link"),
  focusWindow: (target) => ipcRenderer.invoke("ww:focus-window", target),
  openPath: (side, targetPath) => ipcRenderer.invoke("ww:open-path", side, targetPath),
  refresh: (side = null) => ipcRenderer.invoke("ww:refresh", side),
  setHidden: (value) => ipcRenderer.invoke("ww:set-hidden", value),
  connect: (peer) => ipcRenderer.invoke("ww:connect", peer),
  disconnect: () => ipcRenderer.invoke("ww:disconnect"),
  createItem: (side, payload) => ipcRenderer.invoke("ww:create-item", side, payload),
  renameItem: (side, payload) => ipcRenderer.invoke("ww:rename-item", side, payload),
  deleteItems: (side, payload) => ipcRenderer.invoke("ww:delete-items", side, payload),
  listDeletedItems: (side) => ipcRenderer.invoke("ww:list-deleted-items", side),
  restoreDeletedItem: (side, payload) => ipcRenderer.invoke("ww:restore-deleted-item", side, payload),
  transfer: (payload) => ipcRenderer.invoke("ww:transfer", payload),
  explorerOpen: (targetPath = "", side = "local") => ipcRenderer.invoke("ww:explorer-open", targetPath, side),
  explorerOpenRoots: (side = "local") => ipcRenderer.invoke("ww:explorer-open-roots", side),
  explorerClose: () => ipcRenderer.invoke("ww:explorer-close"),
  explorerFetch: (payload) => ipcRenderer.invoke("ww:explorer-fetch", payload),
  recovery: Object.freeze({
    refresh: (options = {}) => ipcRenderer.invoke("ww:recovery-refresh", options),
    selectAgent: (agentId, options = {}) => ipcRenderer.invoke("ww:recovery-select-agent", agentId, options),
    requestInventory: (payload = {}) => ipcRenderer.invoke("ww:recovery-inventory", payload),
    selectCase: (caseId) => ipcRenderer.invoke("ww:recovery-select-case", caseId),
    createCase: (payload) => ipcRenderer.invoke("ww:recovery-case-create", payload),
    updateGoal: (payload) => ipcRenderer.invoke("ww:recovery-goal", payload),
    runCase: (caseId) => ipcRenderer.invoke("ww:recovery-case-run", caseId),
    stopCase: (caseId) => ipcRenderer.invoke("ww:recovery-case-stop", caseId),
    submitCaseAction: (payload) => ipcRenderer.invoke("ww:recovery-case-action", payload),
    expandPlaybook: (payload) => ipcRenderer.invoke("ww:recovery-playbook-expand", payload),
    runPlaybook: (payload) => ipcRenderer.invoke("ww:recovery-playbook-run", payload),
    submitJob: (payload) => ipcRenderer.invoke("ww:recovery-job-submit", payload),
    exec: (payload) => ipcRenderer.invoke("ww:recovery-exec", payload),
    shell: (payload) => ipcRenderer.invoke("ww:recovery-shell", payload),
    cancelJob: (jobId) => ipcRenderer.invoke("ww:recovery-job-cancel", jobId),
    retryJob: (jobId) => ipcRenderer.invoke("ww:recovery-job-retry", jobId),
    upload: (payload) => ipcRenderer.invoke("ww:recovery-artifact-upload", payload),
    download: (payload) => ipcRenderer.invoke("ww:recovery-artifact-download", payload),
    wake: (payload) => ipcRenderer.invoke("ww:recovery-wake", payload),
    pxeStatus: () => ipcRenderer.invoke("ww:recovery-pxe-status"),
    pxePrepare: (payload = {}) => ipcRenderer.invoke("ww:recovery-pxe-prepare", payload),
    pxeStart: (payload = {}) => ipcRenderer.invoke("ww:recovery-pxe-start", payload),
    pxeStop: () => ipcRenderer.invoke("ww:recovery-pxe-stop"),
    setBootPolicy: (payload) => ipcRenderer.invoke("ww:recovery-boot-policy", payload),
    copyText: (value) => ipcRenderer.invoke("ww:recovery-copy-text", value),
    saveText: (payload) => ipcRenderer.invoke("ww:recovery-save-text", payload),
    revealPath: (targetPath) => ipcRenderer.invoke("ww:recovery-reveal-path", targetPath),
  }),
  onEvent: (handler) => {
    const listener = (_event, payload) => handler(payload);
    ipcRenderer.on("ww:event", listener);
    return () => ipcRenderer.removeListener("ww:event", listener);
  },
});
